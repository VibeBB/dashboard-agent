"""mruby/c Emscripten leg: compile UX ``.rb`` sources into the mruby/c VM.

Mirrors the firmware contract's mrubyc pipeline: every authored Ruby file
is compiled to C bytecode with the pinned ``mrbc`` and linked into a
MODULARIZE ES6 module together with the mruby/c core sources and the
upstream ``hal/emscripten`` backend. The node runner then boots the VM
and runs every task to completion.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path

from .mruby_stub import load_stub_spec, render_stub, stub_problems
from .wasm import WasmResult

MRUBYC_DIR_ENV = "DASHBOARD_MRUBYC_DIR"
_MRUBYC_SOURCES = "src"
_EM_HAL = ("hal", "emscripten")
_VALID_STEM = re.compile(r"[^A-Za-z0-9_]")

_SHIM_TEMPLATE = """/* generated by dashboard.mrubyc — do not edit */
#include <stdint.h>
#include <stdio.h>
#include "mrubyc.h"

{externs}
{includes}

static uint8_t memory_pool[{memory_size}];

__attribute__((used)) int
mruby_ux_init(void)
{{
	mrbc_init_alloc(memory_pool, sizeof(memory_pool));
	mrbc_init_global();
	mrbc_init_class();
{defines}
	return 0;
}}

__attribute__((used)) int
mruby_ux_run(void)
{{
{tasks}
	mrbc_run();
	return 0;
}}
"""


def _mrubyc_dir() -> Path:
    return Path(os.environ.get(MRUBYC_DIR_ENV, "/opt/mrubyc"))


def _compile_bytecode(mrbc: str, symbol: str, source: Path, output: Path) -> WasmResult:
    out_c = output / f"{symbol}.c"
    result = subprocess.run(
        [mrbc, "-B", symbol, "--remove-lv", "-o", str(out_c), str(source)],
        capture_output=True,
        timeout=120,
        check=False,
    )
    if result.returncode != 0 or not out_c.is_file():
        detail = result.stderr.decode("utf-8", "replace").strip() or "mrbc -B failed"
        return WasmResult(ok=False, detail=f"{source.name}: {detail}")
    return WasmResult(ok=True, detail=str(out_c))


def build_mrubyc_module(
    root: Path,
    output: Path,
    sources: list[Path],
    memory_size: int,
    api_spec: Path | None = None,
) -> WasmResult:
    """Compile ``sources`` (.rb) into a WASM mruby/c module and boot it in node."""
    emcc = shutil.which("emcc")
    node = shutil.which("node")
    mrbc = shutil.which("mrbc")
    if emcc is None or node is None or mrbc is None:
        missing = [
            name
            for name, value in (("emcc", emcc), ("node", node), ("mrbc", mrbc))
            if value is None
        ]
        return WasmResult(ok=False, detail=f"required tool not found: {', '.join(missing)}")

    mrubyc = _mrubyc_dir()
    core_dir = mrubyc / _MRUBYC_SOURCES
    hal_dir = mrubyc / _EM_HAL[0] / _EM_HAL[1]
    hal_c = hal_dir / "hal.c"
    if not core_dir.is_dir() or not hal_c.is_file():
        return WasmResult(
            ok=False,
            detail=f"mruby/c tree not found under {mrubyc} (set {MRUBYC_DIR_ENV})",
        )
    if api_spec is not None:
        problems = stub_problems(api_spec)
        if problems:
            return WasmResult(ok=False, detail="; ".join(problems))

    output = output.resolve()
    output.mkdir(parents=True, exist_ok=True)

    symbols: list[str] = []
    bytecode_cs: list[Path] = []
    for index, source in enumerate(sources):
        if not source.is_file():
            return WasmResult(ok=False, detail=f"ruby source missing: {source}")
        symbol = _VALID_STEM.sub("_", source.stem) or f"ux_{index}"
        if symbol in symbols:
            symbol = f"{symbol}_{index}"
        symbols.append(symbol)
        compiled = _compile_bytecode(mrbc, symbol, source, output)
        if not compiled.ok:
            return compiled
        bytecode_cs.append(output / f"{symbol}.c")

    includes = ""
    defines = ""
    stub_c: Path | None = None
    if api_spec is not None:
        spec = load_stub_spec(api_spec)
        files = render_stub(spec, api_spec.name)
        api_dir = output / "api"
        api_dir.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (api_dir / name).write_text(text, encoding="utf-8")
        stub_c = api_dir / "dash_api_stub.c"
        includes = '#include "api/dash_api_stub.h"'
        defines = "\tdash_api_define();"

    externs = "\n".join(f"extern const uint8_t {symbol}[];" for symbol in symbols)
    tasks = "\n".join(
        f"\tif (mrbc_create_task({symbol}, 0) == 0) {{\n"
        f'\t\tputs("mruby task create failed: {symbol}");\n'
        f"\t\treturn 1;\n\t}}"
        for symbol in symbols
    )
    shim = output / "mruby_ux_main.c"
    shim.write_text(
        _SHIM_TEMPLATE.format(
            externs=externs,
            includes=includes,
            defines=defines,
            tasks=tasks,
            memory_size=memory_size,
        ),
        encoding="utf-8",
    )

    core_sources = [path for path in core_dir.glob("*.c") if path.name != "hal.c"]
    module = output / "module.mjs"
    built = subprocess.run(
        [
            emcc,
            "-O2",
            f"-I{core_dir}",
            f"-I{hal_dir}",
            *[str(path) for path in sorted(core_sources)],
            str(hal_c),
            *[str(path) for path in bytecode_cs],
            *([str(stub_c)] if stub_c is not None else []),
            str(shim),
            "--no-entry",
            "-sMODULARIZE=1",
            "-sEXPORT_ES6=1",
            "-sEXPORT_NAME=createModule",
            "-sALLOW_MEMORY_GROWTH=1",
            "-sASYNCIFY",
            "-s",
            "EXPORTED_FUNCTIONS=['_mruby_ux_init','_mruby_ux_run','_malloc','_free']",
            "-o",
            str(module),
        ],
        cwd=root,
        capture_output=True,
        text=True,
        timeout=600,
        check=False,
    )
    if built.returncode != 0:
        detail = (built.stderr or built.stdout).strip() or "emcc failed"
        return WasmResult(ok=False, detail=detail)
    return WasmResult(
        ok=True,
        detail=f"built {module.name} with {len(symbols)} ruby source(s)",
    )


def run_mrubyc_module(root: Path, module: Path) -> WasmResult:
    node = subprocess.run(
        ["node", "runtime/test/wasm-mruby-run.mjs", str(module)],
        cwd=root,
        capture_output=True,
        text=True,
        timeout=300,
        check=False,
    )
    detail = (node.stdout + node.stderr).strip() or f"exit code {node.returncode}"
    return WasmResult(ok=node.returncode == 0, detail=detail)
